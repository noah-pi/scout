// Provenance: one plain explanation per image, from its C2PA Content
// Credentials (read by c2pa-web in the offscreen document) and its embedded
// metadata. Pure, so it's testable without a browser.
//
// Absence proves nothing: most platforms strip credentials and metadata on
// upload, so "nothing found" is always said as exactly that.

const IPTC = 'http://cv.iptc.org/newscodes/digitalsourcetype/';
const AI_SOURCES = {
  trainedAlgorithmicMedia: 'generated by AI',
  compositeWithTrainedAlgorithmicMedia: 'edited with AI',
  algorithmicMedia: 'generated by software',
  compositeSynthetic: 'a composite including synthetic elements',
};
const CAPTURE_SOURCES = new Set(['digitalCapture', 'computationalCapture', 'negativeFilm', 'positiveFilm', 'print']);

const GENERATORS = ['Midjourney', 'DALL-E', 'DALL·E', 'Stable Diffusion', 'ComfyUI', 'Adobe Firefly', 'Imagen', 'Gemini', 'ChatGPT', 'OpenAI', 'Flux', 'Ideogram', 'Leonardo', 'NovelAI', 'Google AI'];

const latin1 = (bytes, start = 0, end = bytes.length) => {
  let s = '';
  for (let i = start; i < end; i++) s += String.fromCharCode(bytes[i]);
  return s;
};

export function formatOf(bytes) {
  const h = latin1(bytes, 0, 12);
  if (bytes[0] === 0xff && bytes[1] === 0xd8) return 'jpeg';
  if (h.startsWith('\x89PNG')) return 'png';
  if (h.startsWith('RIFF') && h.slice(8, 12) === 'WEBP') return 'webp';
  if (h.startsWith('GIF8')) return 'gif';
  if (h.slice(4, 8) === 'ftyp') return /avif|avis/.test(h) ? 'avif' : 'bmff';
  return 'unknown';
}

// PNG tEXt / iTXt chunks: where Stable Diffusion UIs and ComfyUI write their
// generation settings.
export function pngText(bytes) {
  const out = {};
  if (formatOf(bytes) !== 'png') return out;
  let i = 8;
  while (i + 12 <= bytes.length) {
    const len = ((bytes[i] << 24) | (bytes[i + 1] << 16) | (bytes[i + 2] << 8) | bytes[i + 3]) >>> 0;
    const type = latin1(bytes, i + 4, i + 8);
    const start = i + 8;
    if (start + len > bytes.length) break;
    if (type === 'tEXt' || type === 'iTXt') {
      const body = latin1(bytes, start, start + len);
      const nul = body.indexOf('\0');
      if (nul > 0) {
        let value = body.slice(nul + 1);
        // iTXt: compression flag, method, language\0, translated keyword\0, text.
        // Compressed iTXt is skipped; generators write it uncompressed.
        if (type === 'iTXt') value = value[0] === '\0' ? value.slice(2).split('\0').slice(2).join('\0') : '';
        if (value) out[body.slice(0, nul)] = value.slice(0, 2000);
      }
    }
    if (type === 'IEND') break;
    i = start + len + 4;
  }
  return out;
}

export function xmpPacket(bytes) {
  const text = latin1(bytes, 0, Math.min(bytes.length, 4 * 1024 * 1024));
  const start = text.indexOf('<x:xmpmeta');
  if (start < 0) return null;
  const end = text.indexOf('</x:xmpmeta>', start);
  if (end < 0) return null;
  try {
    return new TextDecoder().decode(bytes.subarray(start, end + 12));
  } catch {
    return text.slice(start, end + 12);
  }
}

export function sniffMetadata(bytes) {
  const format = formatOf(bytes);
  const xmp = xmpPacket(bytes) ?? '';
  const png = pngText(bytes);
  const sources = [...xmp.matchAll(/digitalsourcetype\/([A-Za-z]+)/g)].map((m) => m[1]);
  const creatorTool = xmp.match(/CreatorTool(?:="|>)([^"<]{1,200})/)?.[1] ?? null;
  const pngKeys = Object.keys(png);
  const haystack = [creatorTool ?? '', png.Software ?? '', png.Description ?? '', png.parameters?.slice(0, 300) ?? ''].join(' ');
  return {
    format,
    sources: [...new Set(sources)],
    creatorTool,
    generators: GENERATORS.filter((g) => haystack.toLowerCase().includes(g.toLowerCase())),
    // Stable Diffusion (A1111/Forge) and ComfyUI leave their settings behind.
    sdParameters: 'parameters' in png && /Steps:|Sampler:|CFG scale/i.test(png.parameters),
    comfyWorkflow: 'workflow' in png || 'prompt' in png,
    // China's GB 45438-2025 implicit label. Field naming is unverified; this
    // looks for an "AIGC" property in XMP or a PNG text key.
    aigcLabel: /AIGC/.test(xmp) || pngKeys.some((k) => /^AIGC$/i.test(k)),
  };
}

function activeManifest(store) {
  return store?.manifests?.[store?.active_manifest] ?? null;
}

function manifestSources(manifest) {
  const out = [];
  for (const a of manifest?.assertions ?? []) {
    if (!/^c2pa\.actions/.test(a.label)) continue;
    for (const action of a.data?.actions ?? []) {
      if (action.digitalSourceType) out.push(String(action.digitalSourceType).replace(IPTC, ''));
    }
  }
  return out;
}

const statusCodes = (store) => [
  ...new Set([...(store?.validation_status ?? []), ...(store?.validation_results?.activeManifest?.failure ?? [])].map((s) => s.code)),
];

// Returns { tone, headline, lines } where tone is one of
// ai | tampered | captured | credentials | none.
export function summarizeProvenance({ store, meta = {}, c2paError = null, triedOriginal = false }) {
  const lines = [];
  const manifest = activeManifest(store);

  if (store?.active_manifest) {
    const signer = manifest?.signature_info?.issuer ?? manifest?.signature_info?.common_name ?? 'an unknown signer';
    const tool = manifest?.claim_generator ? ` with ${String(manifest.claim_generator).replace(/\s*\(.*\)\s*$/, '')}` : '';
    // Trust codes say who signed; the rest say whether anything was altered.
    const codes = statusCodes(store);
    const untrusted = codes.some((c) => /^signingCredential\.(untrusted|invalid|revoked|expired)/.test(c));
    const failures = codes.filter((c) => !/^signingCredential\.untrusted/.test(c));
    if (failures.length || (store.validation_state === 'Invalid' && !untrusted)) {
      const pictureChanged = failures.some((c) => /dataHash\.mismatch|bmffHash\.mismatch|boxesHash\.mismatch/.test(c));
      const credentialChanged = failures.some((c) => /hashedURI\.mismatch|claimSignature\.mismatch|signature/.test(c));
      const headline = pictureChanged
        ? 'Content Credentials present, but the picture was changed after it was signed.'
        : credentialChanged
          ? 'Content Credentials present, but the credential itself was altered.'
          : "Content Credentials present, but they don't verify.";
      return { tone: 'tampered', headline, lines: [`Validation: ${failures.join(', ') || store.validation_state}.`, `Signed by ${signer}${tool}.`] };
    }
    const sources = manifestSources(manifest);
    const ai = sources.find((s) => AI_SOURCES[s]);
    lines.push(`Signed by ${signer}${tool}. Signature checks out.`);
    lines.push(
      untrusted
        ? "The signer isn't on the C2PA trust list, so the file is unaltered since signing, but who signed it can't be confirmed."
        : 'The signer is on the C2PA trust list.',
    );
    if (ai) return { tone: 'ai', headline: `Content Credentials say this image was ${AI_SOURCES[ai]}.`, lines };
    if (sources.some((s) => CAPTURE_SOURCES.has(s))) return { tone: 'captured', headline: 'Content Credentials say this is a camera capture.', lines };
    return { tone: 'credentials', headline: 'Has Content Credentials.', lines };
  }

  const aiMeta = meta.sources?.find((s) => AI_SOURCES[s]);
  const hints = [];
  if (aiMeta) hints.push(`its metadata labels it ${AI_SOURCES[aiMeta]} (IPTC digital source type)`);
  if (meta.sdParameters) hints.push('it carries Stable Diffusion generation settings');
  if (meta.comfyWorkflow) hints.push('it carries a ComfyUI workflow');
  if (meta.aigcLabel) hints.push('it carries what looks like a Chinese AIGC label');
  if (meta.generators?.length) hints.push(`its metadata names ${meta.generators.join(', ')}`);
  if (hints.length) {
    return {
      tone: 'ai',
      headline: 'No Content Credentials, but the file says it was made with AI.',
      lines: [`Unsigned metadata: ${hints.join('; ')}. Anyone can write or remove these fields.`],
    };
  }

  lines.push('Most sites strip credentials and metadata on upload, so this says nothing either way.');
  if (triedOriginal) lines.push('Scout also checked the original-size file.');
  if (c2paError) lines.push(`The credential reader reported: ${c2paError}`);
  lines.push("Invisible watermarks such as Google's SynthID can only be checked with their makers' tools.");
  return { tone: 'none', headline: 'No Content Credentials or AI labels found.', lines };
}

// Google-hosted images (Photos, Blogger, Drive previews) are resized copies
// with metadata stripped; "=d" asks for the original download.
export function originalUrl(url) {
  try {
    const u = new URL(url);
    if (!/(^|\.)googleusercontent\.com$/.test(u.hostname)) return null;
    const m = u.pathname.match(/^(.*?)(=[^/]*)?$/);
    if (!m || m[2] === '=d') return null;
    u.pathname = `${m[1]}=d`;
    return u.toString();
  } catch {
    return null;
  }
}
